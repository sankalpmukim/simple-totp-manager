/**
 * Build and resolve durable element locators.
 *
 * A locator stores several selectors per shadow-root level (stable attributes
 * first, a structural path last) plus a fingerprint of the element's
 * attributes, so it can still be found after a site changes its markup a bit.
 */
import type {
  ElementLocator,
  Fingerprint,
  LocatorStep
} from "../autofill/types"
import {
  deepQueryAll,
  getShadowRoot,
  isShadowRoot,
  isVisible,
  textOf
} from "./dom"

type Root = Document | ShadowRoot

const STABLE_ATTRS = [
  "name",
  "data-testid",
  "data-test",
  "data-test-id",
  "data-qa",
  "data-cy",
  "formcontrolname",
  "aria-label",
  "placeholder"
]

/** ids generated by frameworks (React useId, Ember, MUI, Radix, uuids…) */
function looksDynamic(value: string): boolean {
  return (
    /^:|:$|\d{3,}|[a-f0-9]{8,}|^(ember|react|mui|radix|headlessui|rc_|el-|input-)\d+/i.test(
      value
    ) || value.length > 40
  )
}

function quote(value: string): string {
  return `"${value.replace(/["\\]/g, "\\$&").replace(/\n/g, "\\a ")}"`
}

function isUnique(root: Root, selector: string, el: Element): boolean {
  try {
    const found = root.querySelectorAll(selector)
    return found.length === 1 && found[0] === el
  } catch {
    return false
  }
}

/** tag:nth-of-type chain up to the nearest ancestor with a stable unique id */
function structuralPath(el: Element, root: Root): string {
  const segments: string[] = []
  let cur: Element | null = el
  while (cur && (cur as Node) !== root && cur.parentNode) {
    if (
      cur.id &&
      !looksDynamic(cur.id) &&
      isUnique(root, `#${CSS.escape(cur.id)}`, cur)
    ) {
      segments.unshift(`#${CSS.escape(cur.id)}`)
      break
    }
    const tag = cur.localName
    const parent = cur.parentElement
    if (!parent) {
      segments.unshift(tag)
      break
    }
    const sameTag = Array.from(parent.children).filter(
      (c) => c.localName === tag
    )
    segments.unshift(
      sameTag.length > 1
        ? `${tag}:nth-of-type(${sameTag.indexOf(cur) + 1})`
        : tag
    )
    cur = parent
  }
  return segments.join(" > ")
}

function selectorsFor(el: Element, root: Root): string[] {
  const tag = CSS.escape(el.localName)
  const out: string[] = []
  const add = (selector: string) => {
    if (!out.includes(selector) && isUnique(root, selector, el))
      out.push(selector)
  }

  if (el.id && !looksDynamic(el.id)) add(`#${CSS.escape(el.id)}`)
  for (const attr of STABLE_ATTRS) {
    const value = el.getAttribute(attr)
    if (value && value.length <= 80) add(`${tag}[${attr}=${quote(value)}]`)
  }
  const autocomplete = el.getAttribute("autocomplete")
  if (autocomplete === "one-time-code")
    add(`${tag}[autocomplete="one-time-code"]`)
  if (el.getAttribute("type") === "submit") {
    const form = el.closest("form")
    if (form) {
      const formPath = selectorsFor(form, root)[0]
      if (formPath) add(`${formPath} ${tag}[type="submit"]`)
    }
  }
  add(structuralPath(el, root))
  if (el.id && looksDynamic(el.id)) add(`#${CSS.escape(el.id)}`)
  return out
}

export function fingerprintOf(el: Element): Fingerprint {
  const input = el as HTMLInputElement
  const fp: Fingerprint = { tag: el.localName }
  const set = <K extends keyof Fingerprint>(k: K, v: Fingerprint[K] | null) => {
    if (v !== null && v !== undefined && v !== "") fp[k] = v
  }
  set("type", el.getAttribute("type"))
  set("id", el.id)
  set("name", el.getAttribute("name"))
  set("autocomplete", el.getAttribute("autocomplete"))
  set("inputMode", el.getAttribute("inputmode"))
  set("placeholder", el.getAttribute("placeholder"))
  set("ariaLabel", el.getAttribute("aria-label"))
  if (el.localName === "input" && input.maxLength > 0)
    fp.maxLength = input.maxLength
  if (
    el.localName !== "input" ||
    input.type === "submit" ||
    input.type === "button"
  ) {
    const text = textOf(el).slice(0, 60)
    if (text) fp.text = text
  }
  return fp
}

export function buildLocator(el: Element): ElementLocator {
  const steps: LocatorStep[] = []
  let cur: Element = el
  for (let i = 0; i < 20; i++) {
    const root = cur.getRootNode() as Root
    steps.unshift({ selectors: selectorsFor(cur, root) })
    if (!isShadowRoot(root)) break
    cur = root.host
  }
  return { steps, fingerprint: fingerprintOf(el) }
}

function resolveStep(root: Root, step: LocatorStep): Element | null {
  let fallback: Element | null = null
  for (const selector of step.selectors) {
    let found: NodeListOf<Element>
    try {
      found = root.querySelectorAll(selector)
    } catch {
      continue
    }
    if (found.length === 1) return found[0]
    if (found.length > 1 && !fallback) {
      fallback = Array.from(found).find(isVisible) || null
    }
  }
  return fallback
}

function bySelectors(locator: ElementLocator): Element | null {
  let root: Root = document
  let el: Element | null = null
  for (let i = 0; i < locator.steps.length; i++) {
    el = resolveStep(root, locator.steps[i])
    if (!el) return null
    if (i < locator.steps.length - 1) {
      const sr = getShadowRoot(el)
      if (!sr) return null
      root = sr
    }
  }
  return el
}

function fingerprintScore(fp: Fingerprint, el: Element): number {
  const other = fingerprintOf(el)
  if (other.tag !== fp.tag) return 0
  let score = 0
  if (fp.id && other.id === fp.id) score += 3
  if (fp.name && other.name === fp.name) score += 3
  if (fp.autocomplete && other.autocomplete === fp.autocomplete) score += 2
  if (fp.placeholder && other.placeholder === fp.placeholder) score += 2
  if (fp.ariaLabel && other.ariaLabel === fp.ariaLabel) score += 2
  if (fp.text && other.text === fp.text) score += 3
  if (fp.type && other.type === fp.type) score += 1
  if (fp.inputMode && other.inputMode === fp.inputMode) score += 1
  if (fp.maxLength && other.maxLength === fp.maxLength) score += 1
  return score
}

/** Last resort: the visible element whose attributes best match the fingerprint */
function byFingerprint(fp: Fingerprint): Element | null {
  let best: { el: Element; score: number } | null = null
  for (const el of deepQueryAll(CSS.escape(fp.tag))) {
    if (!isVisible(el)) continue
    const score = fingerprintScore(fp, el)
    if (score >= 3 && (!best || score > best.score)) best = { el, score }
  }
  return best?.el ?? null
}

export interface Resolved {
  el: Element
  /** True when selectors failed and the fingerprint was used */
  fuzzy: boolean
}

export function resolveLocator(locator: ElementLocator): Resolved | null {
  const exact = bySelectors(locator)
  if (exact && isVisible(exact)) return { el: exact, fuzzy: false }
  const fuzzy = byFingerprint(locator.fingerprint)
  if (fuzzy) return { el: fuzzy, fuzzy: true }
  return exact ? { el: exact, fuzzy: false } : null
}
